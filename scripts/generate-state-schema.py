"""Generate the compiler input from the reviewed, shared SQL contract."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
sources = {
    "base": "base-schema-28.sql",
    "shared": "migration-29.sql",
    "triggers": "triggers-v1.sql",
}
generated = "// Generated by scripts/generate-state-schema.py; edit shared-state/*.sql.\n"
for name, filename in sources.items():
    sql = (root / "shared-state" / filename).read_text(encoding="utf-8")
    generated += f"def cli_schema_{name}() -> &str {{ {json.dumps(sql, ensure_ascii=False)} }}\n"
target = root / "src" / "state_schema.sg"
if args.check:
    if target.read_text(encoding="utf-8") != generated:
        raise SystemExit("state_schema.sg differs from shared SQL; regenerate it")
else:
    target.write_text(generated, encoding="utf-8", newline="\n")
